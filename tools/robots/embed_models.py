"""Embed the robot GLBs into outputs/neon-circuit/vendor/models.js as base64.

The game is usually opened straight from disk (file://), where WebGL cannot read
binary files via fetch/XHR, so the models ship inside a classic script instead.
Usage: python embed_models.py [id ...]   (default: every out/*.glb)
"""
import base64
import os
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'vendor' / 'models.js'
ORDER = ['ranger', 'tank', 'assassin', 'drone', 'hunter', 'elite', 'boss']


def main(ids):
    src = pathlib.Path(os.environ.get('MODEL_DIR', HERE / 'out'))
    files = {p.stem: p for p in src.glob('*.glb')}
    wanted = [i for i in (ids or ORDER) if i in files]
    if not wanted:
        sys.exit('no GLB files found in out/')
    parts = []
    for model_id in wanted:
        data = files[model_id].read_bytes()
        if data[:4] != b'glTF':
            sys.exit(f'{model_id}.glb is not a binary glTF file')
        parts.append(f'{json.dumps(model_id)}:"{base64.b64encode(data).decode("ascii")}"')
        print(f'{model_id:9s} {len(data) / 1024:8.1f} KiB')
    OUT.write_text(
        '/* Robot models (Blender GLB, base64). Generated by tools/robots/embed_models.py - do not edit. */\n'
        'window.NEON_MODELS={' + ','.join(parts) + '};\n',
        encoding='ascii')
    print(f'wrote {OUT} ({OUT.stat().st_size / 1024 / 1024:.2f} MiB)')


if __name__ == '__main__':
    main(sys.argv[1:])
